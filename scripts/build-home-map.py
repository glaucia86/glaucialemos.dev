"""Generate the home SVG path from Natural Earth 1:110m land (public domain).

Usage: python scripts/build-home-map.py path/to/ne_110m_land.geojson
Source: https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_110m_land.geojson
Retains the source geometry, rounded to 0.1 SVG unit (0.05 degrees).
Both the land and event points use the same equirectangular projection.
"""
import json
import sys
import re
from pathlib import Path

data = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
paths = []
for feature in data["features"]:
    geometry = feature["geometry"]
    polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
    for polygon in polygons:
        for ring in polygon:
            points = [(round((lon + 180) * 2, 1), round((90 - lat) * 2, 1)) for lon, lat, *_ in ring]
            # Rounding may merge consecutive vertices; remove only exact duplicates.
            unique = [point for i, point in enumerate(points) if i == 0 or point != points[i - 1]]
            paths.append("M" + "L".join(f"{x:g},{y:g}" for x, y in unique) + "Z")

target = Path("public/maps/world-land.svg")
target.parent.mkdir(parents=True, exist_ok=True)
tokens = Path('src/app/tokens.css').read_text(encoding='utf-8')
fill = re.search(r'--color-primary-800:\s*(#[\da-f]+)', tokens)[1]
stroke = re.search(r'--color-primary-500:\s*(#[\da-f]+)', tokens)[1]
target.write_text('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 720 360">\n'
                  + '<!-- Natural Earth 1:110m, public domain. Generated by scripts/build-home-map.py. -->\n'
                  + f'<path id="land" fill="{fill}" stroke="{stroke}" stroke-width="0.8" fill-rule="evenodd" d="' + "".join(paths) + '"/>\n</svg>\n', encoding="utf-8")
print(f"Wrote {target}: {target.stat().st_size} bytes")
